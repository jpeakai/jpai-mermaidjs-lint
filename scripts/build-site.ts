const DOC_FILE = join(PROJECT_ROOT, "doc.md");
const DOC_NAME = "doc.md";
const BANNER = "<!-- Generated by scripts/build-site.ts. Do not edit. -->";

// Every example is scored as a GitHub README would be, named explicitly so an
// mkdocs.yml above the checkout cannot switch the profile.
const GITHUB: RunFlags = { profile: "github" };

// Fixture folders in reading order, with what each one holds. A fixture folder
// missing from this map fails the build, so a new folder arrives described.
export const FIXTURE_GROUPS: Record<string, string> = {
  rules: "One small file per behaviour, named for what it shows.",
  clean: "Files that must report nothing.",
  regressions: "One file per fixed bug, holding the input that once misbehaved.",
  contrast: "Contrast scenarios carried over from an earlier set of diagram-checking scripts.",
  complexity: "Complexity bands and recommendations carried over from an earlier set of diagram-checking scripts.",
  gallery:
    "One diagram of each type, carried over from an earlier set of diagram-checking scripts. All must lint clean.",
  "skill-evals": "Diagrams an earlier set of diagram-checking scripts graded its own output against.",
};

// Small fixtures get every diagram drawn. The large scenario files show their
// findings and source only, or the page would carry hundreds of diagrams.
const DRAW_LIMIT = 3;

// The fixture folders with no description, which fail the build.
export const undescribedFolders = (folders: string[]): string[] => folders.filter((f) => !(f in FIXTURE_GROUPS));

// The folder each test fixture sits in, as the fixtures page groups them. A
// file directly under tests/fixtures/ lands in a folder named "fixtures",
// which has no description, so it fails like an undescribed folder.
export const fixtureFolders = (fixtures: Fixture[]): string[] =>
  [...new Set(fixtures.filter((f) => f.rel.startsWith("tests/")).map((f) => basename(dirname(f.rel))))].sort((a, b) => {
    const order = Object.keys(FIXTURE_GROUPS);
    return (order.indexOf(a) + 1 || order.length + 1) - (order.indexOf(b) + 1 || order.length + 1);
  });

export const failures: string[] = [];
const fail = (where: string, what: string): void => {
  failures.push(`${where}: ${what}`);
};

// ── Markdown helpers ────────────────────────────────────────────────────

// A fence one backtick longer than any run inside the text, so nesting is safe.
const fenced = (text: string, lang: string): string => {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const tick = "`".repeat(longest + 1);
  return `${tick}${lang}\n${text.replace(/\n+$/, "")}\n${tick}`;
};

const indent = (text: string): string =>
  text
    .split("\n")
    .map((l) => (l ? `    ${l}` : l))
    .join("\n");

const admonition = (marker: "!!!" | "???" | "???+", kind: string, title: string, body: string): string =>
  `${marker} ${kind} "${title}"\n\n${indent(body)}\n`;

const tab = (title: string, body: string): string => `=== "${title}"\n\n${indent(body)}\n`;

const cell = (s: string): string => s.replaceAll("|", "\\|").replaceAll("\n", " ");

const badge = (text: string, variant = ""): string =>
  `<span class="ml-badge${variant ? ` ml-badge--${variant}` : ""}">${text}</span>`;

// One card of a before and after comparison: a caption, then the diagram, or
// its source when mermaid could not draw it.
const card = (caption: string, variant: "before" | "after" | "", body: string): string =>
  `<div markdown>\n\n<p class="ml-caption${variant ? ` ml-caption--${variant}` : ""}">${caption}</p>\n\n${body}\n\n</div>`;

const compare = (cards: string[]): string =>
  `<div class="grid ml-compare" markdown>\n\n${cards.join("\n\n")}\n\n</div>\n`;

// Every drawn example is scored under the github profile, so it is drawn the
// way GitHub draws it, not through Material's forced label colour.
const mermaid = (source: string): string => fenced(source, "mermaid-github");

// The lines the CLI prints for these findings, in its own format.
export const reportLines = (findings: Finding[], file: string): string =>
  findings.map((f) => reportLine(f, file)).join("\n");

const findingsTable = (findings: Finding[]): string =>
  [
    "| Line | Rule | Message |",
    "|---:|---|---|",
    ...findings.map((f) => `| ${f.line} | \`${f.rule}\` | ${cell(f.message)} |`),
  ].join("\n");

const distinct = (findings: Finding[]): string[] => [...new Set(findings.map((f) => f.rule))].sort();

// A diagram with a parse finding may draw an error box, and one over a
// node-count limit draws too small to read in a card, so both are shown as
// source instead.
const drawable = (findings: Finding[]): boolean =>
  !findings.some((f) => f.rule.startsWith("parse-") || f.rule.startsWith("complexity-node-count-"));

const titleCase = (s: string): string => `${s[0]?.toUpperCase() ?? ""}${s.slice(1)}`;

// ── Rules page ──────────────────────────────────────────────────────────

const ruleSection = (doc: string, id: string): string => {
  const start = doc.indexOf(`\n### ${id}\n`);
  if (start < 0) return "";
  const rest = doc.slice(start + 1);
  const next = rest.slice(1).search(/\n#{2,3} /);
  return next < 0 ? rest : rest.slice(0, next + 1);
};

const BLOCK = /````text (before|after|reported|llm)\n([\s\S]*?)\n````/g;

const LLM_REASON = /<!--\s*llm:\s*(.*?)\s*-->/;

// An example is checked again as its page is written: it must report, and
// --fix must produce its after, or leave a reported example alone.
const checkRuleExample = async (
  where: string,
  src: string,
  after: string | null,
  llm: CheckedLlmFix | null,
): Promise<Finding[]> => {
  if (after === null && llm === null) fail(where, "a reported example has no LLM fix after it");
  const findings = await checkMarkdown(src, DOC_FILE, GITHUB);
  if (findings.length === 0) fail(where, "an example reports nothing");
  const fixed = await fixSource(src, DOC_FILE, GITHUB);
  if (after === null && fixed !== src) fail(where, "a reported example is changed by --fix");
  if (after !== null && fixed !== after) fail(where, "--fix no longer produces the after example");
  return findings;
};

// The row of cards: the example, what --fix writes, then one card per diagram
// of the LLM fix.
const ruleCards = (src: string, after: string | null, llm: CheckedLlmFix | null, draw: boolean): string[] => {
  const diagramOf = (markdown: string): string => {
    const d = buildDocModel(markdown).diagrams[0];
    return draw && d ? mermaid(d.source) : fenced(markdown, "markdown");
  };
  const cards =
    after === null
      ? [card("Reported, left for a human", "before", diagramOf(src))]
      : [card("Before", "before", diagramOf(src)), card("After --fix", "after", diagramOf(after))];
  // An LLM fix may split one diagram into several, and each gets its own card.
  const llmDiagrams = llm?.diagrams ?? [];
  for (const [i, d] of llmDiagrams.entries()) {
    const label = llmDiagrams.length > 1 ? `LLM fix ${i + 1} of ${llmDiagrams.length}` : "LLM fix";
    cards.push(card(label, "after", mermaid(d)));
  }
  return cards;
};

// The markdown behind the cards, tabbed when there is a second version.
const ruleSource = (src: string, after: string | null, llm: CheckedLlmFix | null): string => {
  if (after !== null)
    return `${tab("Before", fenced(src, "markdown"))}\n${tab("After --fix", fenced(after, "markdown"))}`;
  if (llm) return `${tab("Reported", fenced(src, "markdown"))}\n${tab("LLM fix", fenced(llm.source, "markdown"))}`;
  return fenced(src, "markdown");
};

const ruleExample = async (id: string, src: string, after: string | null, llmSrc: string | null): Promise<string> => {
  const where = `RULES.md ${id}`;
  const llm =
    llmSrc === null
      ? null
      : await llmFix(
          where,
          { path: DOC_FILE, source: llmSrc, reason: LLM_REASON.exec(llmSrc)?.[1] ?? null },
          "markdown",
        );
  const findings = await checkRuleExample(where, src, after, llm);
  const draw = drawable(findings);
  const out = [
    compare(ruleCards(src, after, llm, draw)),
    admonition("!!!", "failure", "What the linter reports", fenced(reportLines(findings, DOC_NAME), "text")),
  ];
  if (llm) out.push(admonition("!!!", "tip", "What an LLM would fix", llm.reason));
  if (draw) out.push(admonition("???", "example", "Markdown source", ruleSource(src, after, llm)));
  return out.join("\n");
};

const optionsLine = (rule: Rule): string => {
  const names = Object.keys(rule.options ?? {});
  if (names.length === 0) return "";
  if (rule.category === "complexity")
    return "Options: `preset` and every threshold, listed in [Config file](configuration.md#complexity-rules).";
  return `Options: ${names.map((n) => `\`${n}\``).join(", ")}, listed in [Config file](configuration.md#rule-options).`;
};

