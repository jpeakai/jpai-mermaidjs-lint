#!/usr/bin/env bun
// Generates the parts of the docs site that the code already knows: the rules
// page, the fixture and example galleries, and snippets (the CLI help, the
// rule table, the preset thresholds) that authored pages include. Each comes
// from the source the test suite runs, and every example is checked again as
// its page is written, so a drifted example fails the build. The one exception
// is the rendered example images, which are only checked to exist.
//
//   bun run scripts/build-site.ts

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { parseArgs } from "node:util";
import {
  buildDocModel,
  CATEGORIES,
  checkMarkdown,
  type Finding,
  fixSource,
  PRESETS,
  RULES,
  type Rule,
} from "../src/index.ts";
import { type Fixture, loadFixtures } from "../tests/fixture-loader.ts";
import { PROJECT_ROOT } from "../tests/helpers.ts";

const SITE = join(PROJECT_ROOT, "docs-site");
const SITE_DOCS = join(SITE, "docs");
const SNIPPETS = join(SITE, "snippets");
const RULES_PATH = join(PROJECT_ROOT, "RULES.md");
// Every example in RULES.md is scored as a GitHub README would be, and shown
// under this name.
const DOC_FILE = join(PROJECT_ROOT, "doc.md");
const DOC_NAME = "doc.md";
const BANNER = "<!-- Generated by scripts/build-site.ts. Do not edit. -->";

// Fixture folders in reading order, with what each one holds.
const FIXTURE_GROUPS: Record<string, string> = {
  rules: "One small file per behaviour, named for what it shows.",
  clean: "Files that must report nothing.",
  contrast: "Contrast scenarios ported from the original skill.",
  complexity: "Complexity bands and recommendations ported from the original skill.",
  gallery: "One diagram of each type, ported from the original skill. All must lint clean.",
  "skill-evals": "The fixtures the original skill graded its own output against.",
};

// Small fixtures get every diagram drawn. The large scenario files show their
// findings and source only, or the page would carry hundreds of diagrams.
const DRAW_LIMIT = 3;

const failures: string[] = [];
const fail = (where: string, what: string): void => {
  failures.push(`${where}: ${what}`);
};

// ── Markdown helpers ────────────────────────────────────────────────────

// A fence one backtick longer than any run inside the text, so nesting is safe.
const fenced = (text: string, lang: string): string => {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const tick = "`".repeat(longest + 1);
  return `${tick}${lang}\n${text.replace(/\n+$/, "")}\n${tick}`;
};

const indent = (text: string): string =>
  text
    .split("\n")
    .map((l) => (l ? `    ${l}` : l))
    .join("\n");

const admonition = (marker: "!!!" | "???" | "???+", kind: string, title: string, body: string): string =>
  `${marker} ${kind} "${title}"\n\n${indent(body)}\n`;

const tab = (title: string, body: string): string => `=== "${title}"\n\n${indent(body)}\n`;

const cell = (s: string): string => s.replaceAll("|", "\\|").replaceAll("\n", " ");

const badge = (text: string, variant = ""): string =>
  `<span class="ml-badge${variant ? ` ml-badge--${variant}` : ""}">${text}</span>`;

// One card of a before and after comparison: a caption, then the diagram, or
// its source when mermaid could not draw it.
const card = (caption: string, variant: "before" | "after" | "", body: string): string =>
  `<div markdown>\n\n<p class="ml-caption${variant ? ` ml-caption--${variant}` : ""}">${caption}</p>\n\n${body}\n\n</div>`;

const compare = (cards: string[]): string =>
  `<div class="grid ml-compare" markdown>\n\n${cards.join("\n\n")}\n\n</div>\n`;

// Every drawn example is scored under the github profile, so it is drawn the
// way GitHub draws it, not through Material's forced label colour.
const mermaid = (source: string): string => fenced(source, "mermaid-github");

const reportLines = (findings: Finding[], file: string): string =>
  findings.map((f) => `${file}:${f.line} ${f.rule} ${f.message}`).join("\n");

const findingsTable = (findings: Finding[]): string =>
  [
    "| Line | Rule | Message |",
    "|---:|---|---|",
    ...findings.map((f) => `| ${f.line} | \`${f.rule}\` | ${cell(f.message)} |`),
  ].join("\n");

const distinct = (findings: Finding[]): string[] => [...new Set(findings.map((f) => f.rule))].sort();

// A diagram with a parse finding may draw an error box, and one over a
// node-count limit draws too small to read in a card, so both are shown as
// source instead.
const drawable = (findings: Finding[]): boolean =>
  !findings.some((f) => f.rule.startsWith("parse-") || f.rule.startsWith("complexity-node-count-"));

const titleCase = (s: string): string => `${s[0]?.toUpperCase() ?? ""}${s.slice(1)}`;

// ── Rules page ──────────────────────────────────────────────────────────

const ruleSection = (doc: string, id: string): string => {
  const start = doc.indexOf(`\n### ${id}\n`);
  if (start < 0) return "";
  const rest = doc.slice(start + 1);
  const next = rest.slice(1).search(/\n#{2,3} /);
  return next < 0 ? rest : rest.slice(0, next + 1);
};

const BLOCK = /````text (before|after|reported)\n([\s\S]*?)\n````/g;

const ruleExample = async (id: string, src: string, after: string | null): Promise<string> => {
  const findings = await checkMarkdown(src, DOC_FILE);
  if (findings.length === 0) fail(`RULES.md ${id}`, "an example reports nothing");
  const fixed = await fixSource(src, DOC_FILE);
  if (after === null && fixed !== src) fail(`RULES.md ${id}`, "a reported example is changed by --fix");
  if (after !== null && fixed !== after) fail(`RULES.md ${id}`, "--fix no longer produces the after example");

  const draw = drawable(findings);
  const diagramOf = (markdown: string): string => {
    const d = buildDocModel(markdown).diagrams[0];
    return draw && d ? mermaid(d.source) : fenced(markdown, "markdown");
  };
  const cards =
    after === null
      ? [card("Reported, left for a human", "before", diagramOf(src))]
      : [card("Before", "before", diagramOf(src)), card("After --fix", "after", diagramOf(after))];

  const out = [
    compare(cards),
    admonition("!!!", "failure", "What the linter reports", fenced(reportLines(findings, DOC_NAME), "text")),
  ];
  if (draw) {
    const source =
      after === null
        ? fenced(src, "markdown")
        : `${tab("Before", fenced(src, "markdown"))}\n${tab("After --fix", fenced(after, "markdown"))}`;
    out.push(admonition("???", "example", "Markdown source", source));
  }
  return out.join("\n");
};

const optionsLine = (rule: Rule): string => {
  const names = Object.keys(rule.options ?? {});
  if (names.length === 0) return "";
  if (rule.category === "complexity")
    return "Options: `preset` and every threshold, listed in [Configuration](configuration.md#complexity-options).";
  return `Options: ${names.map((n) => `\`${n}\``).join(", ")}, listed in [Configuration](configuration.md#rule-options).`;
};

const rulesPage = async (): Promise<string> => {
  const doc = readFileSync(RULES_PATH, "utf8");
  const out: string[] = [
    "# Rules",
    "",
    "Every built-in rule, grouped by what it guards.",
    "Each example shows the exact line the linter prints and, where a fixer exists, what `--fix` writes.",
    "Examples are scored under the `github` profile, so they are drawn the way GitHub draws them.",
    "",
    '!!! info "This page is checked when it is built"',
    "",
    "    The examples come from `RULES.md` in the repository.",
    "    The site build runs each one through the linter, and fails if an example stops reporting its rule or `--fix` stops producing its after.",
    "",
    '--8<-- "rules-table.md"',
    "",
  ];
  for (const category of CATEGORIES) {
    out.push(`## ${titleCase(category)}`, "");
    for (const rule of RULES.filter((r) => r.category === category)) {
      const section = ruleSection(doc, rule.id);
      if (!section) fail("RULES.md", `no section for ${rule.id}`);
      out.push(
        `### ${rule.id}`,
        "",
        `${badge(rule.category)}${rule.fix ? badge("autofix", "fix") : badge("no fixer", "nofix")}`,
        "",
      );
      const prose = section
        .replace(/^### .*\n/, "")
        .replace(BLOCK, "")
        .replace(/\n{3,}/g, "\n\n")
        .trim();
      if (prose) out.push(prose, "");
      const options = optionsLine(rule);
      if (options) out.push(options, "");
      const blocks = [...section.matchAll(BLOCK)].map((m) => ({ kind: m[1] as string, src: `${m[2]}\n` }));
      for (let i = 0; i < blocks.length; i++) {
        const block = blocks[i];
        if (!block || block.kind === "after") continue;
        const next = blocks[i + 1];
        const after = block.kind === "before" && next?.kind === "after" ? next.src : null;
        if (block.kind === "before" && after === null) fail(`RULES.md ${rule.id}`, "a before example has no after");
        out.push(await ruleExample(rule.id, block.src, after), "");
      }
    }
  }
  return out.join("\n");
};

// ── Fixtures page ───────────────────────────────────────────────────────

const fixtureSection = async (f: Fixture): Promise<string> => {
  const findings = await checkMarkdown(f.source, f.path);
  const got = distinct(findings);
  if (f.expected === null) fail(f.rel, "has no expect comment");
  else if (got.join(" ") !== f.expected.join(" "))
    fail(f.rel, `expects ${f.expected.join(" ")} but reports ${got.join(" ")}`);
  const fixed = await fixSource(f.source, f.path);
  if (f.fixed !== null && fixed !== f.fixed) fail(f.rel, "--fix no longer matches its pinned .fixed file");

  const ext = f.path.endsWith(".mmd") ? ".mmd" : ".md";
  const kind = ext === ".mmd" ? "diagram" : "markdown";
  const lang = kind === "diagram" ? "text" : "markdown";
  const out: string[] = [
    `### ${basename(f.rel, ext)}`,
    "",
    `${got.length ? got.map((r) => badge(r)).join("") : badge("clean", "fix")}${f.fixed !== null ? badge("pinned fix", "fix") : ""}`,
    "",
    `[\`${f.rel}\`](https://github.com/jpeakai/jpai-mermaidjs-lint/blob/main/${f.rel})`,
    "",
  ];

  const before = buildDocModel(f.source, kind).diagrams;
  const after = buildDocModel(fixed, kind).diagrams;
  if (before.length > 0 && before.length <= DRAW_LIMIT) {
    for (const [i, d] of before.entries()) {
      const own = findings.filter((x) => x.line >= d.startLine && x.line <= d.endLine);
      // Too big to read in a card, which is the finding: the source below covers it.
      if (own.some((x) => x.rule.startsWith("complexity-node-count-"))) continue;
      const body = drawable(own) ? mermaid(d.source) : fenced(d.source, "text");
      const a = after[i];
      const cards =
        a && a.source !== d.source
          ? [card("Before", "before", body), card("After --fix", "after", mermaid(a.source))]
          : [card(own.length ? "Reported" : "Lints clean", own.length ? "before" : "after", body)];
      out.push(compare(cards));
    }
  }
  if (findings.length)
    out.push(
      admonition(
        before.length > DRAW_LIMIT ? "???" : "???+",
        "failure",
        `${findings.length} finding(s)`,
        findingsTable(findings),
      ),
    );
  out.push(admonition("???", "note", "Source", fenced(f.source, lang)));
  if (fixed !== f.source) out.push(admonition("???", "success", "After --fix", fenced(fixed, lang)));
  return out.join("\n");
};

const fixturesPage = async (): Promise<string> => {
  const fixtures = loadFixtures().filter((f) => f.rel.startsWith("tests/"));
  const folders = [...new Set(fixtures.map((f) => basename(dirname(f.rel))))].sort((a, b) => {
    const order = Object.keys(FIXTURE_GROUPS);
    return (order.indexOf(a) + 1 || order.length + 1) - (order.indexOf(b) + 1 || order.length + 1);
  });
  const out: string[] = [
    "# Fixtures",
    "",
    "The cases the test suite runs, drawn as GitHub renders them.",
    "Each file names the rules it must report, and a pinned fix holds the exact output of `--fix`.",
    "To add a case, see [Add a fixture](index.md#add-a-fixture).",
    "",
  ];
  for (const folder of folders) {
    out.push(`## ${titleCase(folder.replaceAll("-", " "))}`, "", FIXTURE_GROUPS[folder] ?? "", "");
    for (const f of fixtures.filter((x) => basename(dirname(x.rel)) === folder)) out.push(await fixtureSection(f));
  }
  return out.join("\n");
};

// ── Examples page ───────────────────────────────────────────────────────

const examplesPage = async (): Promise<string> => {
  const out: string[] = [
    "# Layout examples",
    "",
    "Layouts, looks and icon packs, from `examples/` in the repository.",
    "Each one lints clean, and the build fails if that changes.",
    "",
    '!!! note "Why these are images"',
    "",
    "    ELK layouts, the hand-drawn look and icon packs need mermaid add-ons a host may not load.",
    "    Each image was drawn with the mermaid CLI, and its source sits beside it.",
    "",
  ];
  for (const f of loadFixtures().filter((x) => x.rel.startsWith("examples/"))) {
    const name = basename(f.path, ".mmd");
    const findings = await checkMarkdown(f.source, f.path);
    if (findings.length) fail(f.rel, `an example must lint clean, but reports ${distinct(findings).join(" ")}`);
    if (!existsSync(join(SITE_DOCS, "assets", "examples", `${name}.png`))) fail(f.rel, "has no rendered image");
    out.push(
      `## ${titleCase(name.replaceAll("_", " "))}`,
      "",
      `![${name}](../assets/examples/${name}.png){ loading=lazy }`,
      "",
      admonition("???", "note", `Source: ${f.rel}`, fenced(f.source, "text")),
    );
  }
  return out.join("\n");
};

// ── Snippets ────────────────────────────────────────────────────────────

const rulesTable = (): string =>
  [
    "| Rule | Category | Autofix | Reports |",
    "|---|---|---|---|",
    ...RULES.map(
      (r) =>
        `| [\`${r.id}\`](rules.md#${r.id}) | ${r.category} | ${r.fix ? "yes" : "no"} | ${cell(titleCase(r.summary))} |`,
    ),
  ].join("\n");

const camel = (snake: string): string => snake.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());

const presetsTable = (): string => {
  const presets = Object.entries(PRESETS).map(([name, values]) => [name, Object.entries(values)] as const);
  const keys = presets[0]?.[1].map(([k]) => k) ?? [];
  return [
    `| Option | ${presets.map(([n]) => `\`${n}\``).join(" | ")} |`,
    `|---|${presets.map(() => "---:").join("|")}|`,
    ...keys.map(
      (k) => `| \`${camel(k)}\` | ${presets.map(([, v]) => String(v.find(([key]) => key === k)?.[1])).join(" | ")} |`,
    ),
  ].join("\n");
};

// The site draws examples with mermaid from a CDN. It must be the version the
// linter parses with, or a diagram the linter reads could fail to draw.
const RENDERER = join(SITE_DOCS, "assets", "mermaid-github.js");

const checkRendererVersion = (): void => {
  const installed = JSON.parse(readFileSync(join(PROJECT_ROOT, "node_modules", "mermaid", "package.json"), "utf8"))
    .version as string;
  const pinned = /mermaid@([\d.]+)\//.exec(readFileSync(RENDERER, "utf8"))?.[1];
  if (pinned !== installed) fail(RENDERER, `loads mermaid ${pinned}, but the linter uses ${installed}`);
};

// The landing page's before and after, taken from a fixture so it is checked
// like every other example.
const HOME_FIXTURE = "tests/fixtures/rules/contrast-text-fixable.md";

const homeCompare = async (): Promise<string> => {
  const f = loadFixtures().find((x) => x.rel === HOME_FIXTURE);
  if (!f || f.fixed === null) {
    fail(HOME_FIXTURE, "the landing example needs this fixture and its pinned fix");
    return "";
  }
  const findings = await checkMarkdown(f.source, f.path);
  const before = buildDocModel(f.source).diagrams[0];
  const after = buildDocModel(f.fixed).diagrams[0];
  if (!before || !after || findings.length === 0) {
    fail(HOME_FIXTURE, "the landing example no longer reports a finding");
    return "";
  }
  return compare([
    card("Before", "before", `${mermaid(before.source)}\n\n${fenced(reportLines(findings, basename(f.rel)), "text")}`),
    card("After --fix", "after", `${mermaid(after.source)}\n\n${fenced("0 finding(s) in 1 file(s)", "text")}`),
  ]);
};

const cliHelp = (): string => {
  const proc = Bun.spawnSync(["bun", join(PROJECT_ROOT, "src", "bin.ts"), "--help"], {
    stdout: "pipe",
    stderr: "pipe",
  });
  if (proc.exitCode !== 0) fail("mermaidjs-lint --help", `exited ${proc.exitCode}`);
  return proc.stdout.toString().replace(/\n+$/, "");
};

// ── Main ────────────────────────────────────────────────────────────────

const HELP = [
  "Usage: bun run scripts/build-site.ts",
  "",
  "Write the generated pages and snippets of the docs site, checking every",
  "example against the tool. Exits 1 when any example has drifted.",
  "",
  "Options:",
  "  -h, --help  Show this help and exit",
].join("\n");

const write = (path: string, body: string): void => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body.endsWith("\n") ? body : `${body}\n`);
};

const main = async (): Promise<void> => {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: { help: { type: "boolean", short: "h", default: false } },
    strict: true,
  });
  if (values.help) {
    console.log(HELP);
    return;
  }

  checkRendererVersion();
  const pages: Record<string, string> = {
    "reference/rules.md": await rulesPage(),
    "gallery/fixtures.md": await fixturesPage(),
    "gallery/examples.md": await examplesPage(),
  };
  const snippets: Record<string, string> = {
    "cli-help.txt": cliHelp(),
    "rules-table.md": rulesTable(),
    "presets-table.md": presetsTable(),
    "home-compare.md": await homeCompare(),
  };
  if (failures.length) {
    console.error(`build-site: ${failures.length} example(s) drifted from the tool:`);
    for (const f of failures) console.error(`  ${f}`);
    process.exit(1);
  }

  for (const [name, body] of Object.entries(pages)) write(join(SITE_DOCS, name), `${BANNER}\n\n${body}`);
  for (const [name, body] of Object.entries(snippets)) write(join(SNIPPETS, name), body);
  console.log(`build-site: wrote ${Object.keys(pages).length} pages and ${Object.keys(snippets).length} snippets`);
};

main().catch((err: unknown) => {
  console.error(`error: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(1);
});
